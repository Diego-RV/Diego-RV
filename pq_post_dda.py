# ============================================================
# 7. Calculate CV
# ============================================================

def calculate_cv(values):

    values = np.asarray(
        values,
        dtype=float
    )

    if len(values) < 2:
        return np.inf

    mean = np.mean(values)

    if mean == 0:
        return np.inf

    return (
        np.std(values, ddof=1)
        / mean
        * 100
    )


