# 8. Calculate RT distance
# ============================================================

def IS_distance(
    feature,
    is_feature,
    rt_tolerance
):

    feature_rt = feature.get("precursor_rt")
    IS_rt = is_feature.get("precursor_rt")

    if (
        feature_rt is None
        or IS_rt is None
    ):
        return np.inf


    rt_distance = abs(feature_rt - IS_rt)

    return ( rt_distance / rt_tolerance)


