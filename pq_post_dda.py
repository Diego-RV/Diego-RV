# Find best match in MSP library for a given feature
#-------------------------------------------------
def find_best_msp_match(
    feature,
    library,
    mz_tolerance,
):

    # ----------------------------------------------
    # Prepare query spectrum
    # ----------------------------------------------
    query = prepare_query_spectrum(feature)

    # ----------------------------------------------
    # Find candidate MSP entries
    # ----------------------------------------------
    candidate_indices = find_msp_candidates(
        feature["precursor_mz"],
        library.mz_sorted,
        library.sorted_idx,
        mz_tolerance,
    )

    if len(candidate_indices) == 0:
        return None

    # ----------------------------------------------
    # Score candidates
    # ----------------------------------------------
    result = score_candidates(
        query,
        feature,
        candidate_indices,
        library,
        mz_tolerance,
    )

    if result is None:
        return None
    
    #Calculate similaririty metrics
    metrics = calculate_similarity_metrics(
        query,
        library.peaks_arrays[result.idx],
    )

    return build_match_record(
        feature=feature,
        annotation=library.annotations[result.idx],
        score=result.score,
        mass_error_ppm=result.mass_error_ppm,
        rmse_mz=result.rmse_mz,
        metrics=metrics,
        query=query,
    )

