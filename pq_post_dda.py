#Preprocess the msp library to speed up the program
#This will remove any annotations with missing m/z and/or retention times
@dataclass
class MSPLibrary:
    annotations: list
    mz_values: np.ndarray
    rt_values: np.ndarray
    peaks_arrays: list
    mz_sorted: np.ndarray
    sorted_idx: np.ndarray

def preprocess_msp_library(msp_data, unknown_classes=True):

    valid_annotations = []

    mz_values = []
    rt_values = []
    peaks_arrays = []

    for annotation in msp_data:

        precursor_mz = annotation.get("precursor_mz")
        retention_time = annotation.get("retention_time")
        peaks = annotation.get("peaks")

        # Skip unknown classes if "unknown_classes" is set to "False"
        if not unknown_classes:
            if annotation.get("class", "").lower() == "unknown":
                continue

        if (
            precursor_mz is None
            or retention_time is None
            or peaks is None
        ):
            continue

        peaks = np.asarray(peaks, dtype=np.float32)

        if peaks.ndim == 3 and peaks.shape[0] == 1:
            peaks = peaks[0]

        if peaks.ndim != 2:
            continue

        valid_annotations.append(annotation)

        mz_values.append(precursor_mz)
        rt_values.append(retention_time)
        peaks_arrays.append(peaks)

    mz_values = np.asarray(mz_values, dtype=np.float32)
    rt_values = np.asarray(rt_values, dtype=np.float32)

    sorted_idx = np.argsort(mz_values)

    return MSPLibrary(
        annotations=valid_annotations,
        mz_values=mz_values,
        rt_values=rt_values,
        peaks_arrays=peaks_arrays,
        mz_sorted=mz_values[sorted_idx],
        sorted_idx=sorted_idx,
    )

#Function to detect internal standards from excel file
def detect_internal_standard(
    feature,
    IS_records,
    IS_mz_tolerance=0.005,
    IS_rt_tolerance=10.0
):

    precursor_mz = feature["precursor_mz"]
    precursor_rt = feature["precursor_rt"]

    best_match = None
    best_score = np.inf

    for record in IS_records:
        IS_mz = record["IS_mz"]
        IS_rt = record["IS_avg_RT"] * 60

        if pd.isna(IS_mz) or pd.isna(IS_rt):
            continue

        IS_mz_distance = abs(
            precursor_mz - IS_mz
        )

        IS_rt_distance = abs(
            precursor_rt - IS_rt
        )

        if (
            IS_mz_distance > IS_mz_tolerance
            or IS_rt_distance > IS_rt_tolerance
        ):
            continue

        IS_match_score = (IS_mz_distance / IS_mz_tolerance + IS_rt_distance / IS_rt_tolerance)/2
        # Added divide by 2 because otherwise the score is between 0 and 2, not 0 and 1
        # Smaller number = closer match or higher score

        if IS_match_score < best_score:

            best_score = IS_match_score

            best_match = {
                "IS_No": record["IS_No"],
                "IS_Name": record["IS_Name"],
                "IS_Class": record["IS_Class"],
                "IS_Adduct": record["IS_Adduct"],
                "IS_predicted_mz": IS_mz, #This is the m/z provided by the file
                "IS_calc_precursor_mz" : precursor_mz, #This is the precursor m/z calculated from the sample
                "IS_calc_avg_ms1_mz" : feature["average_ms1_mz"], #average MS1 m/z from the sample
                "IS_predicted_rt": IS_rt, #This is the RT provided by the file
                "IS_calc_precursor_rt" : precursor_rt, #This is the precursor rt calculated from the sample
                "IS_calc_avg_ms1_rt" : feature["average_ms1_rt"], #average MS1 RT from the sample
                "IS_match_score": float(IS_match_score),
                "IS_mass_error_ppm":
                    ((IS_mz - precursor_mz) / IS_mz)
                    * 1e6
            }

    return best_match

