#1) Average the raw spectra with tolerance of 10 ppm
def average_raw_spectra(
    group,
    ppm_tolerance=10,
    min_fraction=0.5
):

    # ---------------------------------------------------------
    # STEP 1
    # Extract the MS2 spectra belonging to this group.
    #
    # group = ONE peak_id in ONE file_id
    # ---------------------------------------------------------

    spectra = []

    for f in group:

        peaks = np.asarray(f["ms2_sample_peaks"])

        if peaks.size == 0:
            continue

        spectra.append(peaks)

    n_spectra = len(spectra)

    # Need at least two MS2 events
    if n_spectra < 2:
        return np.empty((0, 2))


    # ---------------------------------------------------------
    # STEP 2
    # Calculate the minimum number of MS2 events required
    # to support a fragment.
    #
    # "max(2)" ensures that at least 2 MS2 events are required to support a fragment.
    # This is to prevent a single MS2 event from dominating the consensus spectrum,
    #  which could lead to noise being included in the final result.
    # ---------------------------------------------------------

    min_spectra = max(
        2,
        math.ceil(
            min_fraction * n_spectra
        )
    )


    # ---------------------------------------------------------
    # STEP 3
    # Add the index of the MS2 event to every peak.
    #
    # This lets us keep track of which MS2 events support
    # each fragment.
    # ---------------------------------------------------------

    all_peaks = []

    for spectrum_idx, spectrum in enumerate(spectra):

        for mz, intensity in spectrum:

            all_peaks.append([
                mz,
                intensity,
                spectrum_idx
            ])


    if not all_peaks:
        return np.empty((0, 2))


    all_peaks = np.asarray(all_peaks)


    # ---------------------------------------------------------
    # STEP 4
    # Sort ALL peaks by m/z.
    # ---------------------------------------------------------

    all_peaks = all_peaks[np.argsort(all_peaks[:, 0])]

    # ---------------------------------------------------------
    # STEP 5
    # Build m/z clusters.
    # ---------------------------------------------------------

    mz_clusters = []

    current_mz_cluster = [
        all_peaks[0]
    ]

    for peak in all_peaks[1:]:

        mz = peak[0]

        # Mean m/z of the current group
        group_mz = np.mean([
            p[0]
            for p in current_mz_cluster
        ])

        # Calculate ppm difference
        ppm_error = (
            abs(mz - group_mz)
            / group_mz
            * 1e6
        )


        if ppm_error <= ppm_tolerance:

            current_mz_cluster.append(peak)

        else:

            mz_clusters.append(current_mz_cluster)

            current_mz_cluster = [peak]


    # Add final group
    mz_clusters.append(current_mz_cluster)


    # ---------------------------------------------------------
    # STEP 6
    #Keep only groups supported by enough DISTINCT MS2 events. 
    # ---------------------------------------------------------

    consensus_peaks = []

    for mz_cluster in mz_clusters:

        # Which MS2 events contain this fragment?
        supporting_spectra = {
            int(peak[2])
            for peak in mz_cluster
        }

        n_supporting = len(supporting_spectra)


        # Does it satisfy min_fraction?
        if n_supporting < min_spectra:
            continue


        # -----------------------------------------------------
        # STEP 7
        # Average the m/z and intensity of the retained
        # fragment.
        # -----------------------------------------------------

        consensus_mz = np.mean([
            peak[0]
            for peak in mz_cluster
        ])

        consensus_intensity = np.mean([
            peak[1]
            for peak in mz_cluster
        ])


        consensus_peaks.append([
            consensus_mz,
            consensus_intensity
        ])


    # ---------------------------------------------------------
    # STEP 8
    # Return the consensus spectrum.
    # ---------------------------------------------------------

    if not consensus_peaks:

        return np.empty(
            (0, 2)
        )

    return np.asarray(consensus_peaks)

#2) Calculate entropy statistics 
def calculate_entropy_statistics(group):

    scores = []

    # This is using the weighted entropy similarity with the default centroiding 
    for f1, f2 in combinations(group, 2):

        try:
            score = me.calculate_entropy_similarity(
                f1["ms2_sample_peaks"],
                f2["ms2_sample_peaks"],
            )

            scores.append(score)

        except Exception as e:
            print(
                f"Entropy calculation failed: {e}"
            )

    return {
        "similarity_scores": scores,
        "average_similarity": (
            np.mean(scores)
            if scores else None
        )
    }


#3) Average metadata
def average_metadata(group):

    msms_id = np.array([f["msms_id"] for f in group])

    ms2_rt = np.array([f["ms2_rt"] for f in group])

    return {
        "cluster_id": group[0]["cluster_id"],
        "feature_id": group[0]["feature_id"],
        "peak_id": group[0]["peak_id"],
        "file_id": group[0]["file_id"],

        "msms_id" : msms_id,
        "ms2_rt" : ms2_rt,

        "avg_ms2_rt": np.mean([f["ms2_rt"] for f in group]),

        "precursor_mz": np.mean([f["precursor_mz"] for f in group]),

        "precursor_rt": np.mean([f["precursor_rt"] for f in group]),

        "precursor_intensity": np.mean([f["precursor_intensity"] for f in group]),

        "precursor_vol": np.mean([f["precursor_vol"] for f in group]),
    }

#4) Run all helper functions to average the linked MS2 spectra for MS1 peaks with multiple linked MS2 events
def average_msms(group, ppm_tolerance=10, min_fraction=0.5):

    metadata = average_metadata(group)

    entropy = calculate_entropy_statistics(group)

    avg_ms2_spectra = average_raw_spectra(
        group,
        ppm_tolerance=ppm_tolerance,
        min_fraction=min_fraction
    )

    metadata["entropy_similarity_list"] = entropy["similarity_scores"]
    metadata["avg_entropy_similarity"] = entropy["average_similarity"]
    metadata["avg_raw_ms2_sample_peaks"] = avg_ms2_spectra

    return metadata

def average_linked_ms2(linked_features):

    peak_groups = defaultdict(list)

    # Group MS2 events by ONE peak within ONE file
    for feature in linked_features:

        key = (
            feature["peak_id"],
            feature["file_id"]
        )

        peak_groups[key].append(feature)

    results = []

    for key, group in peak_groups.items():

        new_feature = group[0].copy()

        flags = new_feature["flags"]

        # No linked MS2
        if flags == ["No linked MS2"]:

            new_feature["n_ms2_events"] = 0
            new_feature["avg_ms2_rt"] = None
            new_feature["avg_entropy_similarity"] = None
            new_feature["avg_raw_ms2_sample_peaks"] = np.empty(
                (0, 2),
                dtype=np.float32
            )

            results.append(new_feature)
            continue

        # Average ONLY the MS2 events belonging to
        # this peak_id + file_id combination
        avg_metadata = average_msms(group, ppm_tolerance=10, min_fraction=0.5)

        new_feature.update(avg_metadata)

        new_feature["n_ms2_events"] = len(group)

        results.append(new_feature)

    return results

def aggregate_features(average_linked_ms2):
    """
    Convert peak-level data into feature-level output.

    Rules
    -----
    1. Every peak with linked MS2 is retained as a separate result.
    2. Peaks without linked MS2 are collapsed into one feature-level result.
    3. If a feature has at least one MS2-containing peak, the
       no-MS2 peaks are not given a separate MSP result.
    4. If a feature has no MS2-containing peaks, one feature-level
       no-MS2 result is retained.
    """

    feature_groups = defaultdict(list)

    # --------------------------------------------------
    # Group peaks by file + feature
    # --------------------------------------------------

    for result in average_linked_ms2:

        key = (
            result["file_id"],
            result["feature_id"],
        )

        feature_groups[key].append(result)

    aggregated_features = []

    # --------------------------------------------------
    # Process each feature
    # --------------------------------------------------

    for (file_id, feature_id), group in feature_groups.items():

        # Peaks that have linked MS2
        ms2_peaks = [
            result
            for result in group
            if result.get("n_ms2_events", 0) > 0
        ]

        # Peaks without linked MS2
        no_ms2_peaks = [
            result
            for result in group
             if result.get("n_ms2_events", 0) == 0
        ]

        # ==================================================
        # CASE 1:
        # One or more peaks have MS2
        # ==================================================

        if ms2_peaks:

            # ----------------------------------------------
            # Keep EVERY MS2-containing peak separately
            # ----------------------------------------------

            for result in ms2_peaks:

                output = result.copy()

                output["peak_ids_without_MS2"] = [
                    r["peak_id"]
                    for r in no_ms2_peaks
                ]

                output["peak_id_with_MS2"] = result["peak_id"]

                output["feature_peak_ids"] = sorted(
                    r["peak_id"]
                    for r in group
                )
                
                output["has_ms2"] = True
                
                output["n_ms2_events"] = result["n_ms2_events"]
                
                output["avg_raw_ms2_sample_peaks"] = result["avg_raw_ms2_sample_peaks"]

                aggregated_features.append(output)

        # ==================================================
        # CASE 2:
        # No peaks have MS2
        # ==================================================

        else:

            # ----------------------------------------------
            # Keep ONE representative feature-level result
            # ----------------------------------------------

            representative = no_ms2_peaks[0]

            output = representative.copy()

            output["peak_id_with_MS2"] = "No linked MS2"

            output["feature_peak_ids"] = sorted(
                r["peak_id"]
                for r in group
            )

            output["peak_ids_without_MS2"] = sorted(
                r["peak_id"]
                for r in group
            )

            output["has_ms2"] = False

            output["n_ms2_events"] = 0


            output["avg_raw_ms2_sample_peaks"] = []

            aggregated_features.append(output)

    return aggregated_features

# Function to parse any strings that may be present in the MSP file
def parse_array_from_string(s):
    if isinstance(s, str):
        return np.array([float(x) for x in re.findall(r"[-+]?\d*\.\d+|\d+", s)])
    return np.array([])

def parse_lipid_name(text):

    text = text.strip()

    # Remove leading "low score:" (case-insensitive)
    text = re.sub(
        r"^low score:\s*",
        "",
        text,
        flags=re.IGNORECASE
    )

    # --------------------------------------------------
    # Format 1:
    # e.g.: TG 52:3;O2|TG 16:0_18:1_18:2;O2
    # --------------------------------------------------
    if "|" in text:

        name, chain_info = text.split("|", 1)

        name = name.strip()
        chain_info = chain_info.strip()

        # Extract only the chain composition
        chain_match = re.search(
            r"\d+:\d+(?:_\d+:\d+)+",
            chain_info
        )

        saturation = (
            chain_match.group(0)
            if chain_match
            else None
        )

        return name, saturation

    # --------------------------------------------------
    # Format 2:
    # e.g.: TG 16:0_18:1_18:2;O2
    # --------------------------------------------------

    chain_match = re.search(
        r"\d+:\d+(?:_\d+:\d+)+",
        text
    )

    saturation = (
        chain_match.group(0)
        if chain_match
        else None
    )

    return text, saturation

    # --------------------------------------------------
    # Format 2:
    # e.g.: TG 16:0_18:1_18:2;O2
    # --------------------------------------------------

    chain_match = re.search(
        r"\d+:\d+(?:_\d+:\d+)+",
        text
    )

    saturation = (
        chain_match.group(0)
        if chain_match
        else None
    )

    return text, saturation

