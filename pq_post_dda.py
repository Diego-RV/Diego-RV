# 3. Calculate (approximate)TIC per file
#
# TIC is calculated as the sum of total_intensity values for all clusters in each file.
# ============================================================================================

def calculate_TIC_by_file(aggregated_matches):

    intensities_by_file = defaultdict(list)

    for cluster in aggregated_matches:

        file_id = cluster["file_id"]

        intensity = cluster.get("total_intensity")

        if intensity in (None, 0):
            continue

        intensities_by_file[file_id].append(intensity)

    TIC_by_file = {}

    for file_id, intensities in intensities_by_file.items():

        TIC_by_file[file_id] = sum(intensities)

    return TIC_by_file

