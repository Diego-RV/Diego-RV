# 2. Calculate median IS intensity per file
# ============================================================

def calculate_median_IS_by_file(IS_by_group):

    median_IS_by_file = {}

    for group, ISs in IS_by_group.items():

        IS_intensities_by_file = defaultdict(list)

        for IS in ISs:

            IS_intensity = IS.get("precursor_intensity")

            if IS_intensity in (None, 0):
                continue

            file_id = IS["file_id"]

            IS_intensities_by_file[file_id].append(IS_intensity)

        for file_id, intensities in IS_intensities_by_file.items():

            if intensities:
                median_IS_by_file[file_id] = np.median(intensities)

    return median_IS_by_file

