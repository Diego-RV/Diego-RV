# 2. Change "precursor_type" format to match "IS_Adduct" formatting
# ======================================================================
def normalize_adduct(adduct):
    
    if adduct is None:
        return None

    adduct = str(adduct).strip()

    adduct_mapping = {
        '[M+H]+': 'H+',
        '[M-H]-': 'H-',
        '[M+NH4]+': 'NH4+',
        '[M+HCOO]-': 'HCOO-'
    }

    return adduct_mapping.get(
        adduct,
        adduct
    )
