def aggregate_matches(msp_results):
    """
    Convert peak-level MSP matches into feature-level output.

    Rules
    -----
    1. Feature with MULTIPLE peaks with linked MS2 event(s) +
       library match -> keep peak with highest MSP weighted
       entropy similarity.

    2. Feature with MULTIPLE peaks with linked MS2 event(s) +
       unidentified -> keep peak with highest sample weighted
       entropy similarity.

    3. Feature with ONE peak with linked MS2 event(s) ->
       keep only the MS2-containing peak and collapse the others.

    4. Feature with ZERO peaks with linked MS2 event(s) ->
       collapse into one feature-level no-MS2 result.
    """

    feature_groups = defaultdict(list)

    # --------------------------------------------------
    # Group peaks by file + feature
    # --------------------------------------------------

    for result in msp_results:

        key = (
            result["file_id"],
            result["feature_id"],
        )

        feature_groups[key].append(result)

    aggregated_matches = []

    # --------------------------------------------------
    # Process each feature
    # --------------------------------------------------

    for key, group in feature_groups.items():

        # Peaks that have linked MS2
        ms2_peaks = [
            result
            for result in group
            if result.get("n_ms2_events", 0) > 0
        ]

        # Peaks without linked MS2
        no_ms2_peaks = [
            result
            for result in group
            if result.get("n_ms2_events", 0) == 0
        ]

    # ==================================================
    # CASE 1:
    # One or more peak_ids have linked MS2
    # ==================================================

        if ms2_peaks:

            # --------------------------------------------------
            # Only ONE peak has MS2
            # --------------------------------------------------

            if len(ms2_peaks) == 1:

                selected_result = ms2_peaks[0]

            # --------------------------------------------------
            # MULTIPLE peaks have MS2
            # --------------------------------------------------

            else:

                # ----------------------------------------------
                # Library matches
                # ----------------------------------------------

                library_peaks = [
                    result
                    for result in ms2_peaks
                    if result["classification"] == "library_match"
                    and pd.notna(
                    result["MSP_match"].get("MSP_entropy_similarity")
                    )
                ]

                if library_peaks:

                    selected_result = max(
                        library_peaks,
                        key=lambda r: r["MSP_match"]["MSP_entropy_similarity"]
                    )

                else:

                    # ------------------------------------------
                    # Unidentified / internal standard
                    # ------------------------------------------

                    entropy_peaks = [
                        result
                        for result in ms2_peaks
                        if result["classification"] in {
                        "unidentified",
                        "internal_standard"
                        }
                        and pd.notna(result.get("peak_avg_entropy_similarity"))
                        ]
                    
                    if entropy_peaks:

                        selected_result = max(
                            entropy_peaks,
                            key=lambda r: r["peak_avg_entropy_similarity"]
                        )

                    else:

                        # Fallback
                        selected_result = ms2_peaks[0]

            # --------------------------------------------------
            # Construct output
            # --------------------------------------------------

            output = selected_result.copy()

            output["peak_ids_without_MS2"] = [
                r["peak_id"]
                for r in no_ms2_peaks
            ]

            output["selected_peak_id_with_MS2"] = (
                selected_result["peak_id"]
            )

            output["feature_peak_ids"] = sorted(
                r["peak_id"]
                for r in group
            )

            output["has_ms2"] = True

            output["n_ms2_events"] = (
                selected_result["n_ms2_events"]
            )

            output["cent_ms2_peaks"] = (
                selected_result["cent_ms2_peaks"]
            )

            aggregated_matches.append(output)

                    # ==================================================
        # CASE 2:
        # No peaks have MS2
        # ==================================================

        else:

            # Keep ONE representative feature-level result
            representative = no_ms2_peaks[0]

            output = representative.copy()

            output["selected_peak_id_with_MS2"] = "No linked MS2"

            output["feature_peak_ids"] = sorted(
                r["peak_id"]
                for r in group
            )

            output["peak_ids_without_MS2"] = sorted(
                r["peak_id"]
                for r in group
            )

            output["has_ms2"] = False

            output["n_ms2_events"] = 0

            output["cent_ms2_peaks"] = []

            aggregated_matches.append(output)

    return aggregated_matches

