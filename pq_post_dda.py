# Step 5: Similarity metrics
# -------------------------------------------------
def calculate_similarity_metrics(
    query,
    reference,
):

    if query is None:

        return {
            "entropy": "No MS2",
            "unweighted": "No MS2",
        }

    entropy = me.calculate_entropy_similarity(
        query.peaks,
        reference,
    )

    unweighted = (
        me.calculate_unweighted_entropy_similarity(
            query.peaks,
            reference,
        )
    )

    return {
        "entropy": entropy,
        "unweighted": unweighted,
    }


