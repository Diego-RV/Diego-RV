# -------------------------------------------------
# Step 2: Prepare query spectrum
# -------------------------------------------------
def prepare_query_spectrum(feature):


    n_ms2 = feature.get("n_ms2_events", 0)

    if n_ms2 == 0:
        return None

    peak_key = (
        "ms2_sample_peaks"
        if n_ms2 == 1
        else "avg_raw_ms2_sample_peaks"
    )

    raw_peaks = feature[peak_key]


# Centroid the spectrum using ms_entropy
    peaks = np.asarray(
        me.clean_spectrum(
            raw_peaks,
            min_ms2_difference_in_da=0.02,
            normalize_intensity=False, #"normalize_intensity" is set to false, otherwise intenstities will be between 0 & 1
        ),
        dtype=np.float32,
    )

    return QuerySpectrum(
        peaks=peaks,
        mz=peaks[:, 0],
        intensity=peaks[:, 1],
        peaks_list=peaks.tolist(),
    )


# -------------------------------------------------
# Step 3: Find candidate MSP annotations
# -------------------------------------------------
def find_msp_candidates(
    precursor_mz,
    msp_mz_sorted,
    sorted_idx,
    mz_tolerance,
):

    left = np.searchsorted(
        msp_mz_sorted,
        precursor_mz - mz_tolerance,
        side="left",
    )

    right = np.searchsorted(
        msp_mz_sorted,
        precursor_mz + mz_tolerance,
        side="right",
    )

    return sorted_idx[left:right]


# -------------------------------------------------
# Step 4: Score candidates
# -------------------------------------------------
def score_candidates(
    query,
    feature,
    candidate_indices,
    library,
    mz_tolerance,
):

    best_idx = None
    best_score = np.inf

    precursor_mz = feature["precursor_mz"]


    for idx in candidate_indices:

        mz_distance = abs(
            precursor_mz - library.mz_values[idx]
        )

        if query is None:

            score = ((mz_distance / mz_tolerance) + 1)/2 # Changed this scoring -> 
                                                        # automatic lower score if no MS2

        else:

            reference = library.peaks_arrays[idx]

            if reference is None:
                continue

            entropy = me.calculate_entropy_similarity(
                query.peaks,
                reference,
            )

            score = ((
                mz_distance / mz_tolerance
                + (1 - entropy)
            )/2)
            # Lower score = better score/ closer match

        if score < best_score:

            best_score = score
            best_idx = idx

    if best_idx is None:
        return None

    mass_error_ppm = (
        (library.mz_values[best_idx] - precursor_mz)
        / library.mz_values[best_idx]
    ) * 1e6

    rmse_mz = abs(
        precursor_mz - library.mz_values[best_idx]
    )

    return MatchResult(
    idx=best_idx,
    score=best_score,
    mass_error_ppm=mass_error_ppm,
    rmse_mz=rmse_mz,
)

